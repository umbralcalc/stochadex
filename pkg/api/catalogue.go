// CatalogueVersion is the version of the Catalogue's JSON shape. It changes
// only when a key is removed or its meaning changes; new keys may be added
// within a version. Version 2 made an entry's params a list of objects, and
// added its description and fields.
const CatalogueVersion = 2

// Catalogue describes what this build can run: its version and features, and
// the type name of every component a config can name, read from the
// registries the config resolves through (so downstream registrations, such as
// onnx_inference in a build with the onnx tag, are included). Every list is
// sorted and never null, so the JSON is identical for identical builds.
type Catalogue struct {
	CatalogueVersion int      `json:"catalogue_version"`
	Version          string   `json:"version"`
	Features         []string `json:"features"`
	// Iterations are the iteration: {type: ...} names.
	Iterations []CatalogueEntry `json:"iterations"`
	// DataSources are the keys of a data: or inputs: source, e.g. csv in
	// source: {csv: {...}}.
	DataSources []CatalogueEntry `json:"data_sources"`
	// StreamTransports are the keys of an inputs: stream, e.g. websocket in
	// stream: {websocket: {...}}.
	StreamTransports      []CatalogueEntry `json:"stream_transports"`
	OutputFunctions       []CatalogueEntry `json:"output_functions"`
	OutputConditions      []CatalogueEntry `json:"output_conditions"`
	TerminationConditions []CatalogueEntry `json:"termination_conditions"`
	TimestepFunctions     []CatalogueEntry `json:"timestep_functions"`
	ExecutionStrategies   []CatalogueEntry `json:"execution_strategies"`
	// Macros are the macros: {type: ...} names.
	Macros []CatalogueEntry `json:"macros"`
	// Kernels, Likelihoods, Priors and Jumps are the nested specs composable
	// iterations and macros take, e.g. kernel: {type: exponential}.
	Kernels     []CatalogueEntry `json:"kernels"`
	Likelihoods []CatalogueEntry `json:"likelihoods"`
	Priors      []CatalogueEntry `json:"priors"`
	Jumps       []CatalogueEntry `json:"jumps"`
	// Environments are the mcts_* environment: and mcts_self_play env: names:
	// the engine's own simulation, and those registered with
	// RegisterEnvironment.
	Environments []CatalogueEntry `json:"environments"`
}

// CatalogueEntry is one registered type: what it is, the fields its
// {type: ...} spec takes, and, for an iteration or a component one takes (a
// kernel, a likelihood), the params: it reads from its partition. All of it is
// read from the engine's source (see catalogue_fields.json), so a type
// registered downstream has only its name.
type CatalogueEntry struct {
	Name string `json:"name"`
	// Description is the first sentence of the Go type's doc comment.
	Description string `json:"description,omitempty"`
	// Fields are the keys its spec takes: {type: normal, allow_default_...}.
	Fields []CatalogueField `json:"fields,omitempty"`
	// Params are the names it reads from its partition's params:, which
	// params_from_upstream and params_as_partitions also supply. A name ending
	// in * is a family: transitions_from_* is transitions_from_0, _1, ...
	Params []CatalogueField `json:"params,omitempty"`
	// ParamsIncomplete marks a type that also reads params whose names it
	// builds at run time, so Params does not list them all.
	ParamsIncomplete bool `json:"params_incomplete,omitempty"`
}

// CatalogueField is one key a spec takes or one param a type reads.
type CatalogueField struct {
	Name string `json:"name"`
	// Required marks a spec field that must be given. A param is never marked:
	// whether one must be set can depend on the run's other params.
	Required bool `json:"required,omitempty"`
	// Optional marks a param read only where it may be absent.
	Optional bool `json:"optional,omitempty"`
	// Fields are a nested mapping's own keys, for the typed specs of macros,
	// sources and environments.
	Fields []CatalogueField `json:"fields,omitempty"`
	// Choices are the names a field takes one of (function: data_values),
	// each with what it is and, for a function, the params it reads.
	Choices []CatalogueEntry `json:"choices,omitempty"`
}

// catalogueFieldsJSON is what the engine's source says of each registered
// type, by family and name, generated by TestCatalogueFieldsUpToDate.
//
//go:embed catalogue_fields.json
var catalogueFieldsJSON []byte

// catalogueFields reads catalogueFieldsJSON, which a test keeps valid.
func catalogueFields() map[string]map[string]CatalogueEntry {
	described := map[string]map[string]CatalogueEntry{}
	_ = json.Unmarshal(catalogueFieldsJSON, &described)
	return described
}

// BuildCatalogue reads the catalogue of this build from the registries.
func BuildCatalogue() Catalogue {
	features := append([]string{}, BuildFeatures...)
	sort.Strings(features)
	described := catalogueFields()
	entries := func(family string, lists ...[]string) []CatalogueEntry {
		return catalogueEntries(described[family], lists...)
	}
	return Catalogue{
		CatalogueVersion: CatalogueVersion,
		Version:          BuildVersion,
		Features:         features,
		Iterations: entries("iterations", keys(iterationBuilders), keys(scopedIterationBuilders),
			keys(extraIterationBuilders)),
		DataSources:           entries("data_sources", yamlKeys(reflect.TypeOf(DataSource{})), keys(extraDataSources)),
		StreamTransports:      entries("stream_transports", yamlKeys(reflect.TypeOf(StreamConfig{})), registeredStreamTransportNames()),
		OutputFunctions:       entries("output_functions", simulator.ComponentTypes("output_function")),
		OutputConditions:      entries("output_conditions", simulator.ComponentTypes("output_condition")),
		TerminationConditions: entries("termination_conditions", simulator.ComponentTypes("termination_condition")),
		TimestepFunctions:     entries("timestep_functions", simulator.ComponentTypes("timestep_function")),
		ExecutionStrategies:   entries("execution_strategies", simulator.ComponentTypes("execution_strategy")),
		Macros:                entries("macros", keys(macroSpecFactories)),
		Kernels:               entries("kernels", keys(kernelBuilders)),
		Likelihoods:           entries("likelihoods", keys(likelihoodBuilders)),
		Priors:                entries("priors", keys(priorBuilders)),
		Jumps:                 entries("jumps", keys(jumpBuilders)),
		Environments:          entries("environments", []string{simulationEnvironmentType}, keys(environmentBuilders)),
	}
}

// catalogueEntries merges name lists into sorted, de-duplicated catalogue
// entries, each with what described says of it.
func catalogueEntries(described map[string]CatalogueEntry, lists ...[]string) []CatalogueEntry {
	seen := map[string]bool{}
	for _, names := range lists {
		for _, name := range names {
			seen[name] = true
		}
	}
	result := make([]CatalogueEntry, 0, len(seen))
	for _, name := range keys(seen) {
		entry := described[name]
		entry.Name = name
		result = append(result, entry)
	}
	sort.Slice(result, func(i, j int) bool { return result[i].Name < result[j].Name })
	return result
}

// keys returns a map's keys.
func keys[V any](m map[string]V) []string {
	names := make([]string, 0, len(m))
	for name := range m {
		names = append(names, name)
	}
	return names
}

// yamlKeys returns the YAML keys of a struct's named fields: the spellings it
// declares itself, leaving out its ,inline catch-all for registered ones.
func yamlKeys(t reflect.Type) []string {
	names := []string{}
	for i := 0; i < t.NumField(); i++ {
		name, options, _ := strings.Cut(t.Field(i).Tag.Get("yaml"), ",")
		if name == "" || name == "-" || strings.Contains(options, "inline") {
			continue
		}
		names = append(names, name)
	}
	return names
}

// registeredStreamTransportNames returns the transports registered with
// RegisterStreamTransport.
func registeredStreamTransportNames() []string {
	streamTransportsMu.RLock()
	defer streamTransportsMu.RUnlock()
	return keys(streamTransports)
}
